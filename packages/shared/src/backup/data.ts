import { z } from 'zod';
import {
  accountInputSchema,
  amountPeriodInputSchema,
  categoryInputSchema,
  categoryRuleInputSchema,
  occurrenceInputSchema,
  recurringItemInputSchema,
  transactionInputSchema,
  type SyncEntity,
} from '../dto/records';
import {
  allocationRuleInputSchema,
  goalContributionInputSchema,
  goalInputSchema,
  loanInputSchema,
  loanLedgerInputSchema,
  plannedPaymentInputSchema,
  receivableInputSchema,
  scenarioInputSchema,
} from '../dto/planning';

/** The readable form of an export: every synced record, grouped by type. */
export const DATA_FORMAT = 'zerodue-data';

/** Parents before the records that point at them, so a restore never writes a dangling reference. */
export const RESTORE_ORDER: readonly SyncEntity[] = [
  'account',
  'category',
  'categoryRule',
  'recurringItem',
  'recurringAmountPeriod',
  'loan',
  'loanLedgerEntry',
  'loanPlannedPayment',
  'scenario',
  'receivable',
  'goal',
  'goalContribution',
  'allocationRule',
  'transaction',
  'recurringOccurrence',
];

/**
 * Due dates are generated by the server from each bill, so restoring them would collide with the
 * ones it creates. They stay in exports, and are skipped on restore.
 */
export const NOT_RESTORED: readonly SyncEntity[] = ['recurringOccurrence'];

const INPUT_SCHEMAS: Record<SyncEntity, z.ZodTypeAny> = {
  account: accountInputSchema,
  category: categoryInputSchema,
  categoryRule: categoryRuleInputSchema,
  transaction: transactionInputSchema,
  recurringItem: recurringItemInputSchema,
  recurringAmountPeriod: amountPeriodInputSchema,
  recurringOccurrence: occurrenceInputSchema,
  loan: loanInputSchema,
  loanLedgerEntry: loanLedgerInputSchema,
  loanPlannedPayment: plannedPaymentInputSchema,
  scenario: scenarioInputSchema,
  receivable: receivableInputSchema,
  goal: goalInputSchema,
  goalContribution: goalContributionInputSchema,
  allocationRule: allocationRuleInputSchema,
};

export type DataTables = Record<SyncEntity, Record<string, unknown>[]>;

export interface DataDocument {
  format: typeof DATA_FORMAT;
  version: 1;
  exportedAt: string;
  tables: Partial<DataTables>;
}

export function buildDataDocument(
  tables: Partial<DataTables>,
  exportedAt: Date | string,
): DataDocument {
  return {
    format: DATA_FORMAT,
    version: 1,
    exportedAt: new Date(exportedAt).toISOString(),
    tables,
  };
}

const documentSchema = z.object({
  format: z.literal(DATA_FORMAT),
  version: z.number().int(),
  exportedAt: z.string(),
  tables: z.record(z.string(), z.array(z.unknown())),
});

export interface ParsedData {
  exportedAt: string;
  /** Records ready to write, keyed by type. Metadata is dropped; only the fields a client may write remain. */
  records: Record<SyncEntity, Record<string, unknown>[]>;
  /** Rows that were left out because they are not valid, described for the user. */
  problems: string[];
}

export function parseDataDocument(text: string): ParsedData {
  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    throw new Error('This is not a ZeroDue data file.');
  }
  const doc = documentSchema.safeParse(json);
  if (!doc.success) throw new Error('This is not a ZeroDue data file.');
  if (doc.data.version !== 1) throw new Error('This data is from a newer version of ZeroDue.');

  const records = Object.fromEntries(
    RESTORE_ORDER.map((e) => [e, []]),
  ) as unknown as ParsedData['records'];
  const problems: string[] = [];
  for (const entity of RESTORE_ORDER) {
    const rows = doc.data.tables[entity] ?? [];
    rows.forEach((row, index) => {
      const id = (row as { id?: unknown } | null)?.id;
      const parsed = INPUT_SCHEMAS[entity].safeParse(row);
      if (!parsed.success || typeof id !== 'string') {
        problems.push(`${entity} #${index + 1} is not valid and was left out`);
        return;
      }
      records[entity].push({ ...(parsed.data as Record<string, unknown>), id });
    });
  }
  return { exportedAt: doc.data.exportedAt, records, problems };
}
